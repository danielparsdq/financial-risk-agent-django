def load_dotenv(dotenv_path: Path) -> None:
    if not dotenv_path.exists():
        return

    with dotenv_path.open(encoding="utf-8") as env_file:
        for raw_line in env_file:
            line = raw_line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue

            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip('"').strip("'")

            if key and key not in os.environ:
                os.environ[key] = value


load_dotenv(BASE_DIR / ".env")


def get_bool(env_name: str, default: str = "false") -> bool:
    return os.getenv(env_name, default).lower() in {"1", "true", "yes", "on"}


def get_list(env_name: str, default: str = "") -> list[str]:
    return [item.strip() for item in os.getenv(env_name, default).split(",") if item.strip()]


